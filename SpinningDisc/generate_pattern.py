"""Bake logarithmic spiral coordinates and shaded tile colors for the ESP32.
Requires NumPy. Generates original math-based artwork, not a resized reference.
"""
from pathlib import Path
import argparse
import numpy as np

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--output-dir', type=Path, default=Path(__file__).resolve().parent)
out = parser.parse_args().output_dir
out.mkdir(parents=True, exist_ok=True)

def rgb565(rgb):
    rgb = np.clip(rgb, 0, 255).astype(np.uint32)
    return ((rgb[...,0]>>3)<<11) | ((rgb[...,1]>>2)<<5) | (rgb[...,2]>>3)

# One warm tile and one teal tile, with rolling highlights and shaded edges.
v, u = np.mgrid[:256, :256].astype(float)/255
curvature = .11*np.sin(v*np.pi)*np.sin(u*np.pi)
t = np.clip(u+curvature, 0, 1)
stops = [0, .25, .57, .82, 1]
warm = [[118,30,32], [211,55,29], [251,131,31], [255,204,92], [250,235,176]]
cool = [[13,53,67], [20,112,126], [45,167,172], [137,211,195], [218,237,199]]
tiles = []
for colors in [warm, cool]:
    rgb = np.stack([np.interp(t, stops, np.array(colors)[:,c]) for c in range(3)], axis=-1)
    shade = .86+.14*np.sin(v*np.pi)
    rgb *= shade[...,None]
    # Fine ordered dithering avoids large banded regions in RGB565 gradients.
    dither = np.array([[0,2],[3,1]])[np.indices((256,256))[0]%2,np.indices((256,256))[1]%2]-1.5
    rgb += dither[...,None]*1.1
    tiles.append(rgb565(rgb))
tiles = np.asarray(tiles)
curve = np.rint(68*np.sin(np.arange(256)*np.pi/256)).astype(np.int16)

y, x = np.mgrid[:240,:240].astype(float)
dx, dy = x-119.5, y-119.5
r = np.sqrt(dx*dx+dy*dy)
angle = np.arctan2(dy,dx)/(2*np.pi)
log_radius = np.log(np.maximum(r, 9)/9)
# Integer winding counts make the polar seam continuous through every rotation.
coord_u = np.rint((18*angle+3.3*log_radius)*256).astype(np.int32)&511
coord_v = np.rint((4.2*log_radius-4*angle)*256).astype(np.int32)&511
edge = np.clip(119.5-r, 0, 1)
shade = np.rint(255*edge).astype(np.uint32)
coordinates = coord_u.astype(np.uint32) | (coord_v.astype(np.uint32)<<9) | (shade<<18)
coordinates[r>=119.5] = 0x80000000

# A fixed glassy teal hub: light comes from upper left as the disc turns below.
ball_radius = 11.5
nx, ny = dx/ball_radius, dy/ball_radius
nz = np.sqrt(np.maximum(0, 1-nx*nx-ny*ny))
diffuse = np.clip(-.43*nx-.55*ny+.72*nz, 0, 1)
specular = np.clip(-.30*nx-.38*ny+.87*nz, 0, 1)**35
ball = np.stack([7+38*diffuse+195*specular,
                 16+111*diffuse+139*specular,
                 20+119*diffuse+130*specular],axis=-1)
ball *= (.25+.75*nz)[...,None]
ball_color = rgb565(ball)
ball_mask = r<=ball_radius
coordinates[ball_mask] = 0x80000000 | ball_color[ball_mask]
rim = (r>ball_radius)&(r<ball_radius+1)
coordinates[rim] = 0x80000000 | rgb565(np.array([13,30,32]))

with (out/'DiscTables.h').open('w') as f:
    f.write('// Generated by generate_pattern.py. Original procedural artwork.\n')
    f.write('#pragma once\n#include <stdint.h>\n#ifdef ARDUINO\n#include <pgmspace.h>\n#else\n#define PROGMEM\n#endif\nnamespace DiscTables {\n')
    f.write('constexpr int ANGULAR_TILES=18, CROSS_SPIRALS=4;\n')
    for name, arr, kind in [('COORDINATES', coordinates, 'uint32_t'),
                            ('TILES', tiles, 'uint16_t'), ('CURVE', curve, 'int16_t')]:
        flat = arr.ravel()
        f.write(f'const {kind} {name}[{len(flat)}] PROGMEM = {{\n')
        for i in range(0,len(flat),24):
            f.write(','.join(str(int(n)) for n in flat[i:i+24])+',\n')
        f.write('};\n')
    f.write('}\n')
print('Generated polar geometry, two shaded tile palettes and a glossy central hub.')
