"""Bake the big digital-face glyphs into DigitFont.h as 8-bit alpha masks.

Source: assets/Nunito-wght.ttf (SIL Open Font License, assets/OFL.txt),
rendered at weight 900 so digits are 180 px tall. Requires Pillow.
"""
from pathlib import Path
import argparse
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent
parser = argparse.ArgumentParser(description=__doc__)
# Windows Controlled Folder Access can block Python from creating files under
# Documents; write elsewhere and copy the header in if that happens.
parser.add_argument('--output-dir', type=Path, default=ROOT)
OUT = parser.parse_args().output_dir
FONT = ROOT / 'assets' / 'Nunito-wght.ttf'
WEIGHT = 900
DIGIT_HEIGHT = 180
CHARS = '0123456789:-'


def load(size):
    font = ImageFont.truetype(str(FONT), size)
    font.set_variation_by_axes([WEIGHT])
    return font


# Find the point size whose digits are DIGIT_HEIGHT pixels tall.
probe = load(200)
left, top, right, bottom = probe.getbbox('0', anchor='ls')
size = round(200 * DIGIT_HEIGHT / (bottom - top))
font = load(size)
_, digit_top, _, digit_bottom = font.getbbox('0', anchor='ls')

glyphs, data = [], bytearray()
for ch in CHARS:
    # Crop to the ink so the face can space glyphs tightly; tabular advances
    # make ":07" wider than the screen.
    canvas = Image.new('L', (2 * size, 2 * size), 0)
    baseline = size
    ImageDraw.Draw(canvas).text((size // 2, baseline), ch, fill=255, font=font, anchor='ls')
    left, top, right, bottom = canvas.getbbox()
    image = canvas.crop((left, top, right, bottom))
    glyphs.append(dict(ch=ch, offset=len(data), width=right - left, height=bottom - top,
                       x=0, y=top - (baseline + digit_top), advance=right - left))
    data += image.tobytes()

lines = [
    '// Generated by prepare_assets.py from Nunito (SIL Open Font License). Do not edit.',
    '#pragma once',
    '#include <stdint.h>',
    '',
    'namespace DigitFont {',
    '// x: left bearing from the pen; y: top relative to the top of the digits.',
    'struct Glyph { char ch; uint32_t offset; int16_t width, height, x, y, advance; };',
    f'constexpr int DIGIT_HEIGHT = {digit_bottom - digit_top};',
    f'constexpr int GLYPH_COUNT = {len(glyphs)};',
    'constexpr Glyph GLYPHS[GLYPH_COUNT] = {',
]
for g in glyphs:
    lines.append(f"  {{'{g['ch']}', {g['offset']}, {g['width']}, {g['height']}, {g['x']}, {g['y']}, {g['advance']}}},")
lines += ['};', f'alignas(4) constexpr uint8_t ALPHA[{len(data)}] = {{']
for i in range(0, len(data), 24):
    lines.append('  ' + ','.join(str(b) for b in data[i:i + 24]) + ',')
lines += ['};', '}  // namespace DigitFont', '']
OUT.mkdir(parents=True, exist_ok=True)
(OUT / 'DigitFont.h').write_text('\n'.join(lines), newline='\n')
print(f'Wrote DigitFont.h: {len(glyphs)} glyphs at {size} pt, {len(data)} bytes of alpha.')
